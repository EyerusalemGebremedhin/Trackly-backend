import enum
from datetime import datetime

from sqlalchemy import Column, Integer, DateTime, ForeignKey, Enum, Text

from database import Base


class FeedbackSource(str, enum.Enum):
    lead = "lead"
    ai = "ai"


class Feedback(Base):
    """
    Feedback / improvement notes about one person's progress.
    Either written by a lead, or generated by the AI analyzer.
    Optionally tied to a specific task or check-in for context.
    """
    __tablename__ = "feedback"

    id = Column(Integer, primary_key=True, index=True)
    about_user_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    given_by_id = Column(Integer, ForeignKey("users.id"), nullable=True)  # null when source == ai
    source = Column(Enum(FeedbackSource), default=FeedbackSource.lead, nullable=False)

    content = Column(Text, nullable=False)
    task_id = Column(Integer, ForeignKey("tasks.id"), nullable=True)
    checkin_id = Column(Integer, ForeignKey("checkins.id"), nullable=True)

    created_at = Column(DateTime, default=datetime.utcnow)
